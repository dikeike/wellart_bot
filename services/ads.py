from services.billing import add_credits

# -----------------------------------------------------
# Симуляция просмотра рекламы
# -----------------------------------------------------
AD_REWARD = 2  # сколько кредитов за рекламу

def watch_ad(user_id: int) -> int:
    """
    Заглушка рекламы.
    В реальности здесь будет ссылка на рекламную сеть.
    """
    add_credits(user_id, AD_REWARD)
    return AD_REWARD